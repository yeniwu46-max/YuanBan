// Run with: playwright-cli -s=ybb-accept run-code --filename scripts/ui-forest-acceptance.js
async (page) => {
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 const results=[]
 const assert=(ok,message)=>{if(!ok)throw new Error(message);results.push(message)}
 const nav=path=>page.goto('http://127.0.0.1:5182/#'+path)
 const button=name=>page.getByRole('button',{name,exact:true})
 async function login(role){
  await nav('/pages/login-role/index')
  await page.getByRole('button',{name:role==='elder'?/我是老人/:role==='family'?/我是家人/:/我是社区人员/}).click()
  await button('登录并继续').click()
  await button(role==='family'?'继续 ›':'保存信息 ›').click()
  if(role==='elder'){await button('完成绑定 ✓').click();await button('进入首页').click()}
  else await button(role==='family'?'进入守护首页 ⌂':'进入服务工作台 ⌂').click()
  await page.getByRole('navigation').waitFor()
 }
 async function layout(label){
  for(const width of [320,390,768,1024,1440]){
   await page.setViewportSize({width,height:900})
   await page.screenshot({path:`output/playwright/forest-${label}-${width}.png`,scale:'css'})
   const size=await page.evaluate(()=>({body:document.documentElement.scrollWidth,width:innerWidth,nav:[...document.querySelectorAll('[role=navigation]')].filter(el=>el.getClientRects().length).length}))
   assert(size.body<=size.width+1,`${label} ${width}px no horizontal overflow (${size.body})`)
   assert(size.nav===1,`${label} ${width}px one navigation`)
  }
  await page.setViewportSize({width:390,height:844})
 }
 await page.setViewportSize({width:390,height:844})
 await page.goto('http://127.0.0.1:5182');await page.reload()
 await login('elder')
 await layout('elder')
 const sosBox=await button('紧急求助').boundingBox()
 assert(sosBox && sosBox.y+sosBox.height<740,'elder SOS visible in first screen')
 await nav('/pkg-elder-detail/medicine/index')
 await button('我已服药').click()
 await page.getByText(/已记录为已服用/).waitFor()
 await nav('/pages/home/index');await nav('/pkg-elder-detail/medicine/index')
 assert(await page.getByText(/已记录为已服用/).isVisible(),'medicine record survives navigation')
 await nav('/pkg-elder-detail/activity/index');await button('报名参加').click();await button('已报名').waitFor()
 assert(true,'activity enrollment feedback')
 await nav('/pages/companion/index');await button('开心').click();await page.getByText('今天：开心',{exact:true}).waitFor()
 assert(true,'mood record updates')
 await nav('/pkg-elder-detail/bp/index')
 await page.getByRole('img',{name:/血压趋势/}).waitFor()
 await page.getByRole('button',{name:/展开完整记录/}).click()
 assert(await page.getByText('128 / 82 mmHg',{exact:true}).isVisible(),'BP chart and records agree')
 await nav('/pkg-elder-detail/sos/index');await button('误触了，取消').click();await page.getByText('已取消本次操作',{exact:true}).waitFor()
 await button('重新求助').click();await button('确认，立即求助').click();await page.getByText('求助已提交',{exact:true}).waitFor()
 await page.screenshot({path:'output/playwright/forest-sos-success.png'})
 assert(true,'SOS cancel and submitted states')
 await login('family');await layout('family')
 await page.getByRole('button',{name:/李奶奶发起 SOS 求助/}).click()
 await button('已处理').click();await page.waitForURL('**/pages/tabs/tab0/index');await page.getByRole('navigation',{name:'家人守护'}).waitFor()
 assert(true,'family received and resolved new demo SOS')
 await button('报告').click();await page.getByRole('tab',{name:'日报',exact:true}).click()
 await page.getByRole('tab',{name:'日报',exact:true}).press('ArrowRight')
 assert(await page.getByRole('tab',{name:'周报',exact:true}).getAttribute('aria-selected')==='true','report tabs support keyboard')
 await button('切换守护对象').click();await page.getByRole('dialog').waitFor()
 await page.waitForFunction(()=>document.querySelector('[role="dialog"]')?.contains(document.activeElement))
 assert(await page.getByRole('dialog').evaluate(el=>el.contains(document.activeElement)),'sheet receives focus')
 await page.getByRole('button',{name:/王爷爷 75 岁/}).click()
 await page.getByText('该长辈在此时间范围内暂无有效血压记录。',{exact:true}).waitFor()
 assert(true,'elder switch does not reuse another elder curve')
 await button('切换守护对象').click();await page.keyboard.press('Escape')
 await page.getByRole('dialog').waitFor({state:'hidden'})
 assert(await button('切换守护对象').evaluate(el=>document.activeElement===el),'sheet Escape restores focus')
 await button('设置').click()
 const toggle=page.getByRole('switch').first();const before=await toggle.getAttribute('aria-checked');await toggle.focus();await toggle.press('Space')
 assert(await toggle.getAttribute('aria-checked')!==before,'notification switch supports keyboard')
 await button('关怀').click();await button('设置').click()
 assert(await page.getByRole('switch').first().getAttribute('aria-checked')!==before,'notification setting survives navigation')
 await login('community');await layout('community')
 await button('工单').click();await page.getByRole('button',{name:/李奶奶发起 SOS 求助/}).click()
 await button('确认现场情况并完成').click();const resultRadio=page.getByRole('radio',{name:'已联系，确认长辈安全',exact:true});await resultRadio.focus();await resultRadio.press('Space');await button('确认完成工单').click()
 await button('工单已完成').waitFor();assert(true,'community completes SOS after result confirmation')
 await button('工单').click();await page.getByRole('tab',{name:'已完成',exact:true}).click()
 assert(await page.getByRole('button',{name:/李奶奶发起 SOS 求助/}).isVisible(),'completed workorder visible in completed filter')
 await page.setViewportSize({width:1440,height:900});await page.getByRole('table').waitFor()
 assert(true,'desktop workorders use semantic table')
 assert(!await page.locator('.mobile-only').isVisible(),'desktop does not duplicate mobile list')
 await page.screenshot({path:'output/playwright/forest-workorders-desktop.png'})
 await page.getByRole('textbox',{name:'搜索事项、工单编号或地址'}).fill('不存在的工单')
 await page.getByText('没有匹配的工单。试试其他分类，或清空搜索内容。',{exact:true}).waitFor()
 assert(true,'search empty state')
 await page.context().setOffline(true);await page.getByText('当前离线，已加载内容仍可查看。联网后可重试。',{exact:true}).waitFor();await page.context().setOffline(false)
 assert(true,'offline banner')
 await page.emulateMedia({reducedMotion:'reduce'})
 assert(await page.evaluate(()=>matchMedia('(prefers-reduced-motion: reduce)').matches),'reduced motion enabled')
 await page.setViewportSize({width:844,height:390})
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'landscape no overflow')
 assert(errors.length===0,'no JavaScript runtime errors: '+errors.join('; '))
 return {passed:results.length,results}
}
